import { formatOklch } from "@/lib/color";
import { dark, fontSize, light, motion, radius, shadow, type ColorScheme } from "./tokens";

const kebab = (value: string) => value.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);

function colorVars(scheme: ColorScheme, indent: string): string {
  return Object.entries(scheme)
    .map(([name, value]) => `${indent}--aq-${kebab(name)}: ${formatOklch(value)};`)
    .join("\n");
}

/** Renders src/styles/tokens.css. Run `pnpm tokens:build` after editing tokens.ts. */
export function renderTokensCss(): string {
  const lines = [
    "/* Generated by `pnpm tokens:build` from src/design/tokens.ts. Do not edit. */",
    "",
    ":root {",
    "  color-scheme: light;",
    colorVars(light, "  "),
    ...Object.entries(radius).map(([k, v]) => `  --aq-radius-${k}: ${v};`),
    ...Object.entries(shadow).map(([k, v]) => `  --aq-shadow-${k}: ${v};`),
    ...Object.entries(motion).map(([k, v]) => `  --aq-motion-${kebab(k)}: ${v};`),
    ...Object.entries(fontSize).map(([k, v]) => `  --aq-text-${k}: ${v};`),
    "}",
    "",
    ':root[data-theme="dark"] {',
    "  color-scheme: dark;",
    colorVars(dark, "  "),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    "    color-scheme: dark;",
    colorVars(dark, "    "),
    "  }",
    "}",
    "",
  ];
  return lines.join("\n");
}
